const assert = require('node:assert/strict');
const {comparison, shift, autoWindow} = require('../usage/usage.js');
const counts = fresh => ({fresh, read:100, write:0, output:0});
const today = '2026-10-26';
const days = new Map([[today, counts(9999999)], [shift(today,-1), counts(10)], [shift(today,-2), counts(1)]]);
assert.equal(autoWindow(today, shift(today,-3)), 1);
assert.equal(autoWindow(today, shift(today,-6)), 3);
assert.equal(autoWindow(today, shift(today,-20)), 7);
assert.deepEqual(comparison(days,today,1,shift(today,-3),'fresh'), {current:10,prior:1,change:900});
assert.deepEqual(comparison(days,today,1,shift(today,-3),'read'), {current:100,prior:100,change:0});
days.set(shift(today,-2), counts(100));
assert.deepEqual(comparison(days,today,1,shift(today,-3),'fresh'), {current:10,prior:100,change:-90});
assert.deepEqual(comparison(days,today,7,shift(today,-14),'fresh'), {current:110/7,prior:0,change:null});
assert.deepEqual(comparison(days,today,7,shift(today,-2)), {current:null,prior:null,change:null});
console.log('Trend checks passed (rising, falling, zero baseline, missing history, empty days, metric, today and DST).');
const row = (fresh, priced, cost) => ({...counts(fresh), read:0, priced_tokens:priced, usd:{fresh:cost}});
const priceDays = new Map([[shift(today,-1),row(100,90,3)], [shift(today,-2),row(30,30,6)]]);
assert.deepEqual(comparison(priceDays,today,1,shift(today,-4),'cost'), {current:3,prior:6,change:-50});
priceDays.set(shift(today,-1),row(100,0,0));
assert.deepEqual(comparison(priceDays,today,1,shift(today,-4),'cost'), {current:null,prior:6,change:null});
priceDays.delete(shift(today,-1));
assert.deepEqual(comparison(priceDays,today,1,shift(today,-4),'cost'), {current:0,prior:6,change:-100});
